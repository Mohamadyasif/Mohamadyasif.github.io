const modal = document.getElementById("projectModal");
const modalTitle = document.getElementById("modalTitle");
const modalKicker = document.getElementById("modalKicker");
const modalIntro = document.getElementById("modalIntro");
const modalContent = document.getElementById("modalContent");

function openProject(key) {
  const project = projects[key];
  if (!project) return;
  modalKicker.textContent = project.kicker;
  modalTitle.textContent = project.title;
  modalIntro.textContent = project.intro;
  modalContent.innerHTML = project.blocks.map(([heading, content]) => {
    const body = Array.isArray(content)
      ? `<ul>${content.map(item => `<li>${item}</li>`).join("")}</ul>`
      : `<p>${content}</p>`;
    return `<section class="modal-block"><h3>${heading}</h3>${body}</section>`;
  }).join("");
  modal.classList.add("open");
  modal.setAttribute("aria-hidden", "false");
  document.body.style.overflow = "hidden";
  document.getElementById("modalClose").focus();
}
function closeProject() {
  modal.classList.remove("open");
  modal.setAttribute("aria-hidden", "true");
  document.body.style.overflow = "";
}
document.querySelectorAll(".project-open").forEach(button => {
  button.addEventListener("click", () => openProject(button.dataset.project));
});
document.getElementById("modalClose").addEventListener("click", closeProject);
document.getElementById("modalDone").addEventListener("click", closeProject);
modal.addEventListener("click", event => { if (event.target === modal) closeProject(); });
document.addEventListener("keydown", event => { if (event.key === "Escape") closeProject(); });

document.querySelectorAll(".filter").forEach(button => {
  button.addEventListener("click", () => {
    document.querySelectorAll(".filter").forEach(item => item.classList.remove("active"));
    button.classList.add("active");
    const filter = button.dataset.filter;
    document.querySelectorAll(".project-card").forEach(card => {
      card.hidden = filter !== "all" && !card.dataset.category.split(" ").includes(filter);
    });
  });
});

const menuToggle = document.getElementById("menuToggle");
const navLinks = document.getElementById("navLinks");
menuToggle.addEventListener("click", () => {
  const expanded = menuToggle.getAttribute("aria-expanded") === "true";
  menuToggle.setAttribute("aria-expanded", String(!expanded));
  navLinks.classList.toggle("open", !expanded);
});
navLinks.querySelectorAll("a").forEach(link => link.addEventListener("click", () => {
  navLinks.classList.remove("open");
  menuToggle.setAttribute("aria-expanded", "false");
}));
